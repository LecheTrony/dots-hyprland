#!/usr/bin/env bash
# theme-profile.sh — save / list / apply / delete full desktop style profiles.
#
# A "profile" captures the whole look at once:
#   - wallpaper (image copied into the profile, or the path for videos)
#   - dark / light mode
#   - Material You scheme type (scheme-tonal-spot, scheme-content, ...)
#   - desktop widgets (position, size, which ones are enabled)
#   - appearance settings (transparency, fonts, palette, ...)
#
# The widget + appearance part is restored by merging the profile's snapshot of
# ~/.config/illogical-impulse/config.json back into the live config. The colors
# are re-generated by calling the regular switchwall.sh entry point.
#
# Usage:
#   theme-profile.sh save <name>
#   theme-profile.sh apply <name>
#   theme-profile.sh delete <name>
#   theme-profile.sh rename <old> <new>
#   theme-profile.sh list              # human readable
#   theme-profile.sh list --json       # machine readable (used by the settings UI)
#   theme-profile.sh current           # json describing the live state
#
set -euo pipefail

XDG_CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
XDG_STATE_HOME="${XDG_STATE_HOME:-$HOME/.local/state}"
SHELL_CONFIG_FILE="$XDG_CONFIG_HOME/illogical-impulse/config.json"
PROFILES_DIR="$XDG_CONFIG_HOME/illogical-impulse/theme-profiles"
STATE_DIR="$XDG_STATE_HOME/quickshell"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SWITCHWALL="$SCRIPT_DIR/switchwall.sh"

# Keys of config.json that make up the "style" of a profile.
# background.widgets  -> desktop widget layout
# appearance          -> transparency, fonts, palette, theming toggles
# background.{screenList,widgetsLocked} -> extra layout state
SNAPSHOT_QUERY='{
  background: {
    widgets: .background.widgets,
    widgetsLocked: .background.widgetsLocked,
    screenList: .background.screenList
  },
  appearance: .appearance
}'

die() { echo "[theme-profile] $*" >&2; exit 1; }
log() { echo "[theme-profile] $*" >&2; }

require_jq() { command -v jq >/dev/null 2>&1 || die "jq is required but was not found in PATH"; }

ensure_dirs() { mkdir -p "$PROFILES_DIR"; }

# Resolve the profile directory for a name, rejecting anything that escapes it.
profile_dir() {
    local name="$1"
    [[ -n "$name" ]] || die "empty profile name"
    # Allow letters, numbers, space, dash, underscore, dot. No slashes.
    if [[ "$name" == *"/"* || "$name" == ".." || "$name" == "." ]]; then
        die "invalid profile name: '$name'"
    fi
    echo "$PROFILES_DIR/$name"
}

current_mode() {
    local mode
    mode="$(gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | tr -d "'" || true)"
    if [[ "$mode" == "prefer-dark" ]]; then
        echo "dark"
    else
        echo "light"
    fi
}

current_type() {
    jq -r '.appearance.palette.type // "auto"' "$SHELL_CONFIG_FILE" 2>/dev/null || echo "auto"
}

current_wallpaper() {
    jq -r '.background.wallpaperPath // ""' "$SHELL_CONFIG_FILE" 2>/dev/null || echo ""
}

current_thumbnail() {
    jq -r '.background.thumbnailPath // ""' "$SHELL_CONFIG_FILE" 2>/dev/null || echo ""
}

is_video() {
    local ext="${1##*.}"
    case "${ext,,}" in
        mp4|webm|mkv|avi|mov) return 0 ;;
        *) return 1 ;;
    esac
}

mkdir_profile() {
    local dir="$1"
    mkdir -p "$dir"
}

# ---------------------------------------------------------------------------
# save
# ---------------------------------------------------------------------------
cmd_save() {
    require_jq
    ensure_dirs
    local name="$1"
    [[ -n "$name" ]] || die "usage: theme-profile.sh save <name>"
    local dir
    dir="$(profile_dir "$name")"

    [[ -f "$SHELL_CONFIG_FILE" ]] || die "shell config not found: $SHELL_CONFIG_FILE"

    local wallpaper thumbnail mode type
    wallpaper="$(current_wallpaper)"
    thumbnail="$(current_thumbnail)"
    mode="$(current_mode)"
    type="$(current_type)"

    mkdir_profile "$dir"

    # Snapshot style-relevant parts of the config.
    jq "$SNAPSHOT_QUERY" "$SHELL_CONFIG_FILE" > "$dir/config.snapshot.json"

    # Wallpaper: copy images into the profile so it survives file moves.
    # Videos stay referenced by path (they can be huge and are handled by mpvpaper).
    local stored_wallpaper="$wallpaper"
    if [[ -n "$wallpaper" && -f "$wallpaper" ]]; then
        if is_video "$wallpaper"; then
            log "video wallpaper: storing reference only"
            stored_wallpaper="$wallpaper"
        else
            local ext="${wallpaper##*.}"
            cp -f "$wallpaper" "$dir/wallpaper.$ext"
            stored_wallpaper="__PROFILE__/wallpaper.$ext"
        fi
        if [[ -n "$thumbnail" && -f "$thumbnail" ]]; then
            cp -f "$thumbnail" "$dir/thumbnail.jpg"
        fi
    fi

    # Metadata.
    jq -n \
        --arg name "$name" \
        --arg created "$(date -Is)" \
        --arg wallpaper "$stored_wallpaper" \
        --arg originalWallpaper "$wallpaper" \
        --arg mode "$mode" \
        --arg type "$type" \
        '{name: $name, created: $created, wallpaper: $wallpaper, originalWallpaper: $originalWallpaper, mode: $mode, type: $type}' \
        > "$dir/profile.json"

    log "saved profile '$name' ($mode / $type)"
    echo "$name"
}

# ---------------------------------------------------------------------------
# apply
# ---------------------------------------------------------------------------
cmd_apply() {
    require_jq
    local name="$1"
    [[ -n "$name" ]] || die "usage: theme-profile.sh apply <name>"
    local dir
    dir="$(profile_dir "$name")"
    [[ -d "$dir" ]] || die "profile '$name' does not exist"
    [[ -f "$dir/profile.json" ]] || die "profile '$name' is corrupt (missing profile.json)"
    [[ -f "$dir/config.snapshot.json" ]] || die "profile '$name' is corrupt (missing config.snapshot.json)"

    local mode type wallpaper
    mode="$(jq -r '.mode // "dark"' "$dir/profile.json")"
    type="$(jq -r '.type // "auto"' "$dir/profile.json")"
    wallpaper="$(jq -r '.wallpaper // ""' "$dir/profile.json")"

    # Resolve the profile-local wallpaper reference.
    if [[ "$wallpaper" == __PROFILE__/* ]]; then
        local rel="${wallpaper#__PROFILE__/}"
        wallpaper="$dir/$rel"
    fi

    # 1. Restore widgets + appearance into the live config.
    #    Deep-merge only the profile-owned keys, keeping unrelated live keys.
    local tmp
    tmp="$(mktemp)"
    jq --slurpfile snap "$dir/config.snapshot.json" \
        '.background.widgets = $snap[0].background.widgets
         | .background.widgetsLocked = $snap[0].background.widgetsLocked
         | .background.screenList = $snap[0].background.screenList
         | .appearance = $snap[0].appearance' \
        "$SHELL_CONFIG_FILE" > "$tmp" && mv "$tmp" "$SHELL_CONFIG_FILE"

    # 2. Point the config at the profile wallpaper. switchwall.sh --noswitch reads
    #    background.wallpaperPath from the config, so set it first.
    if [[ -n "$wallpaper" && -f "$wallpaper" ]]; then
        tmp="$(mktemp)"
        jq --arg path "$wallpaper" '.background.wallpaperPath = $path' "$SHELL_CONFIG_FILE" > "$tmp" \
            && mv "$tmp" "$SHELL_CONFIG_FILE"
    fi

    # 3. Re-apply wallpaper + colors + mode + scheme type.
    "$SWITCHWALL" --mode "$mode" --type "$type" --noswitch

    # QuickShell watches config.json (FileView with watchChanges), so the widget
    # layout updates by itself once the file above is written. No reload needed.

    log "applied profile '$name' ($mode / $type)"
    echo "$name"
}

# ---------------------------------------------------------------------------
# delete / rename
# ---------------------------------------------------------------------------
cmd_delete() {
    local name="$1"
    [[ -n "$name" ]] || die "usage: theme-profile.sh delete <name>"
    local dir
    dir="$(profile_dir "$name")"
    [[ -d "$dir" ]] || die "profile '$name' does not exist"

    # If the live config points at this profile's stored wallpaper, move it back
    # to the original location so we don't leave a dangling path behind.
    if [[ -f "$dir/profile.json" && -f "$SHELL_CONFIG_FILE" ]] && command -v jq >/dev/null 2>&1; then
        local stored original current
        stored="$(jq -r '.wallpaper // ""' "$dir/profile.json")"
        original="$(jq -r '.originalWallpaper // ""' "$dir/profile.json")"
        current="$(current_wallpaper)"
        if [[ "$stored" == __PROFILE__/* && "$current" == "$dir/${stored#__PROFILE__/}" && -n "$original" ]]; then
            local tmp
            tmp="$(mktemp)"
            jq --arg path "$original" '.background.wallpaperPath = $path' "$SHELL_CONFIG_FILE" > "$tmp" \
                && mv "$tmp" "$SHELL_CONFIG_FILE"
            log "live wallpaper pointed at this profile; restored to '$original'"
        fi
    fi

    rm -rf "$dir"
    log "deleted profile '$name'"
    echo "$name"
}

cmd_rename() {
    local old="$1" new="$2"
    [[ -n "$old" && -n "$new" ]] || die "usage: theme-profile.sh rename <old> <new>"
    local olddir newdir
    olddir="$(profile_dir "$old")"
    newdir="$(profile_dir "$new")"
    [[ -d "$olddir" ]] || die "profile '$old' does not exist"
    [[ -e "$newdir" ]] && die "profile '$new' already exists"
    mv "$olddir" "$newdir"
    if [[ -f "$newdir/profile.json" ]] && command -v jq >/dev/null 2>&1; then
        jq --arg name "$new" '.name = $name' "$newdir/profile.json" > "$newdir/profile.json.tmp" \
            && mv "$newdir/profile.json.tmp" "$newdir/profile.json"
    fi
    log "renamed profile '$old' -> '$new'"
    echo "$new"
}

# ---------------------------------------------------------------------------
# list / current
# ---------------------------------------------------------------------------
# Emits a JSON array of profiles, newest first.
profiles_json() {
    ensure_dirs
    local dir
    local out="[]"
    for dir in "$PROFILES_DIR"/*/; do
        [[ -d "$dir" ]] || continue
        [[ -f "$dir/profile.json" ]] || continue
        out="$(jq --argjson acc "$out" --slurpfile p "$dir/profile.json" \
            '$acc + [$p[0]]' -n)"
    done
    echo "$out" | jq 'sort_by(.created) | reverse'
}

cmd_list() {
    require_jq
    if [[ "${1:-}" == "--json" ]]; then
        profiles_json
        return
    fi
    local count
    count="$(profiles_json | jq 'length')"
    if [[ "$count" == "0" ]]; then
        echo "(no profiles saved yet)"
        return
    fi
    profiles_json | jq -r '.[] | "\(.name)\t\(.mode)/\(.type)\t\(.created)"' | column -t -s $'\t'
}

cmd_current() {
    require_jq
    [[ -f "$SHELL_CONFIG_FILE" ]] || die "shell config not found: $SHELL_CONFIG_FILE"
    jq -n \
        --arg wallpaper "$(current_wallpaper)" \
        --arg mode "$(current_mode)" \
        --arg type "$(current_type)" \
        --argjson widgets "$(jq '.background.widgets | to_entries | map(select(.value | type == "object") | select(.value.enable == true)) | map(.key)' "$SHELL_CONFIG_FILE")" \
        '{wallpaper: $wallpaper, mode: $mode, type: $type, enabledWidgets: $widgets}'
}

usage() {
    cat <<EOF
theme-profile.sh — full desktop style profiles

Usage:
  theme-profile.sh save <name>          Save current style as <name>
  theme-profile.sh apply <name>         Apply <name> (widgets + colors + wallpaper)
  theme-profile.sh delete <name>        Delete <name>
  theme-profile.sh rename <old> <new>   Rename a profile
  theme-profile.sh list [--json]        List saved profiles
  theme-profile.sh current              Show current style as JSON

Profiles are stored in:
  $PROFILES_DIR
EOF
}

main() {
    local cmd="${1:-}"
    shift || true
    case "$cmd" in
        save)   cmd_save "$@" ;;
        apply)  cmd_apply "$@" ;;
        delete) cmd_delete "$@" ;;
        rename) cmd_rename "$@" ;;
        list)   cmd_list "$@" ;;
        current) cmd_current "$@" ;;
        ""|-h|--help|help) usage ;;
        *) die "unknown command: '$cmd' (try --help)" ;;
    esac
}

main "$@"
